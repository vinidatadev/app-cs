CREATE OR REPLACE FUNCTION public.slugify(txt text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT trim(both '.' from regexp_replace(lower(unaccent(coalesce(txt, ''))), '[^a-z0-9]+', '.', 'g'));
$$;

CREATE OR REPLACE FUNCTION public.seed_app_auth_for_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  base_name text;
  candidate text;
  suffix int := 0;
BEGIN
  IF NEW.id_user IS NULL THEN
    RETURN NEW;
  END IF;

  IF EXISTS (SELECT 1 FROM public.app_auth WHERE id_user = NEW.id_user) THEN
    RETURN NEW;
  END IF;

  base_name := nullif(public.slugify(NEW.nome_usuario), '');
  IF base_name IS NULL THEN
    base_name := 'usuario';
  END IF;

  candidate := base_name;
  WHILE EXISTS (SELECT 1 FROM public.app_auth WHERE lower(username) = lower(candidate)) LOOP
    suffix := suffix + 1;
    candidate := base_name || suffix::text;
  END LOOP;

  INSERT INTO public.app_auth (id_user, username, email, display_name, password_hash)
  VALUES (
    NEW.id_user,
    candidate,
    candidate || '@organograma.local',
    NEW.nome_usuario,
    crypt('organograma123', gen_salt('bf'))
  )
  ON CONFLICT DO NOTHING;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_app_auth_name()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.nome_usuario IS DISTINCT FROM OLD.nome_usuario THEN
    UPDATE public.app_auth
    SET display_name = NEW.nome_usuario
    WHERE id_user = NEW.id_user;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_seed_app_auth ON public."user";
CREATE TRIGGER trg_seed_app_auth
AFTER INSERT ON public."user"
FOR EACH ROW EXECUTE FUNCTION public.seed_app_auth_for_user();

DROP TRIGGER IF EXISTS trg_sync_app_auth_name ON public."user";
CREATE TRIGGER trg_sync_app_auth_name
AFTER UPDATE OF nome_usuario ON public."user"
FOR EACH ROW EXECUTE FUNCTION public.sync_app_auth_name();
